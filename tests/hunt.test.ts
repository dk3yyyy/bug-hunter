describe("applyVerdict", () => {
  const candidate: FindingT & { id: string } = {
    id: "f1",
    file: "a.ts",
    start_line: 10,
    end_line: 12,
    severity: "high",
    category: "bug",
    confidence: 0.8,
    title: "Title Here",
    explanation: "explain",
    evidence_quote: "  code",
    fix_kind: "none",
    fix_code: null,
  };

  it("is deterministic", () => {
    expect(fingerprint(candidate)).toBe(fingerprint(candidate));
    expect(fingerprint(candidate)).toMatch(/^[0-9a-f]{40}$/);
  });

  it("drops findings the verifier rejects", () => {
    const verdict: VerdictT = {
      results: [
        {
          id: "f1",
          verdict: "drop",
          reason: "unreachable",
          adjusted_severity: null,
          adjusted_confidence: 0.1,
          corrected_start_line: null,
          corrected_end_line: null,
          fix_ok: false,
        },
      ],
    };
    const { kept, exorcised } = applyVerdict([candidate], verdict);
    expect(kept).toHaveLength(0);
    expect(exorcised).toEqual([{ id: "f1", title: "Title Here", severity: "high", reason: "unreachable" }]);
  });

  it("applies downgrade adjustments and corrected lines", () => {
    const verdict: VerdictT = {
      results: [
        {
          id: "f1",
          verdict: "downgrade",
          reason: "overstated",
          adjusted_severity: "medium",
          adjusted_confidence: 0.55,
          corrected_start_line: 11,
          corrected_end_line: 11,
          fix_ok: true,
        },
      ],
    };
    const { kept } = applyVerdict([candidate], verdict);
    expect(kept).toHaveLength(1);
    const k = kept[0];
    expect(k.adjusted_severity).toBe("medium");
    expect(k.severity).toBe("high");
    expect(k.adjusted_confidence).toBe(0.55);
    expect(k.start_line).toBe(11);
    expect(k.end_line).toBe(11);
    expect(k.position).toBeNull();
    expect(k.fingerprint).toBe(fingerprint(candidate));
  });

  it("treats a missing verdict as fail-closed (exorcised, never posted)", () => {
    const verdict: VerdictT = { results: [] };
    const { kept, exorcised } = applyVerdict([candidate], verdict);
    expect(kept).toHaveLength(0);
    expect(exorcised).toEqual([
      { id: "f1", title: "Title Here", severity: "high", reason: "no verdict returned" },
    ]);
  });
});

