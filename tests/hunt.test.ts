describe("filterFiles", () => {
  it("skips lockfiles and build/vendor dirs with reasons", () => {
    const files = [
      file("package-lock.json"),
      file("yarn.lock"),
      file("dist/app.js", { patch: "const a = 1;" }),
      file("node_modules/x/index.js", { patch: "const b = 2;" }),
      file("vendor/lib.js", { patch: "const c = 3;" }),
      file("src/app.min.js", { patch: "const d = 4;" }),
      file("src/app.js.map", { patch: "const e = 5;" }),
      file("src/candy.ts", { patch: "const ok = 1;" }),
    ];
    const { kept, skipped } = filterFiles(files);

    expect(kept.map((f) => f.filename)).toEqual(["src/candy.ts"]);

    const reasons = new Map(skipped.map((s) => [s.path, s.reason]));
    expect(reasons.get("package-lock.json")).toBe("lockfile");
    expect(reasons.get("yarn.lock")).toBe("lockfile");
    expect(reasons.get("dist/app.js")).toBe("build/vendor/dependency directory");
    expect(reasons.get("node_modules/x/index.js")).toBe("build/vendor/dependency directory");
    expect(reasons.get("vendor/lib.js")).toBe("build/vendor/dependency directory");
    expect(reasons.get("src/app.min.js")).toBe("minified file");
    expect(reasons.get("src/app.js.map")).toBe("source map");
  });

  it("skips binaries and auto-generated files", () => {
    const files = [
      file("img/logo.png", { isBinary: true }),
      file("src/large.bin"),
      file("src/generated.ts", { patch: "@@ -1 +1 @@\n// @generated by codegen\n+const x = 1;" }),
      file("src/DONTEDIT.ts", { patch: "@@ -1 +1 @@\n// DO NOT EDIT\n+const y = 1;" }),
      file("src/normal.ts", { patch: "@@ -1 +1 @@\n+const z = 1;" }),
    ];
    const { kept, skipped } = filterFiles(files);

    expect(kept.map((f) => f.filename)).toEqual(["src/normal.ts"]);
    expect(skipped.map((s) => s.path)).toEqual([
      "img/logo.png",
      "src/large.bin",
      "src/generated.ts",
      "src/DONTEDIT.ts",
    ]);
  });

  it("orders kept files source > tests > config > docs", () => {
    const files = [
      file("README.md", { patch: "# hi" }),
      file("src/config.json", { patch: "{}" }),
      file("src/candy.test.ts", { patch: "test('x')" }),
      file("src/candy.ts", { patch: "export const x = 1" }),
    ];
    const { kept } = filterFiles(files);
    expect(kept.map((f) => f.filename)).toEqual([
      "src/candy.ts",
      "src/candy.test.ts",
      "src/config.json",
      "README.md",
    ]);
  });

  it("caps kept files at 40 and skips the overflow", () => {
    const files = Array.from({ length: 45 }, (_, i) =>
      file(`src/f${i}.ts`, { patch: `export const f${i} = ${i};` }),
    );
    const { kept, skipped } = filterFiles(files);

    expect(kept).toHaveLength(40);
    expect(skipped).toHaveLength(5);
    expect(skipped.every((s) => s.reason === "over 40-file limit")).toBe(true);
  });
});

