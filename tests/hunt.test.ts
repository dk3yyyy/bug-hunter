function file(filename: string, opts: { patch?: string; isBinary?: boolean; hunks?: Hunk[] } = {}): ChangedFile {
  return {
    filename,
    status: "modified",
    additions: 0,
    deletions: 0,
    patch: opts.patch,
    hunks: opts.hunks ?? [],
    isBinary: opts.isBinary ?? false,
  };
}

